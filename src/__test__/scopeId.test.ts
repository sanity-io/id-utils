import {sha256 as nobleSha256} from '@noble/hashes/sha2.js'
import {afterEach, describe, expect, test, vi} from 'vitest'

import {createScopeId} from '../scopeId'
import {
  SHA256_IMPLEMENTATIONS,
  useSha256Implementation,
} from './sha256Implementations'

vi.mock('@noble/hashes/sha2.js', async importOriginal => {
  const actual = await importOriginal<{sha256: typeof nobleSha256}>()
  return {...actual, sha256: vi.fn(actual.sha256)}
})

describe('createScopeId() SHA-256 implementation', () => {
  afterEach(() => {
    vi.restoreAllMocks()
    vi.mocked(nobleSha256).mockClear()
    vi.unstubAllGlobals()
  })

  test('prefers Web Crypto when it is available', async () => {
    const digest = vi.spyOn(globalThis.crypto.subtle, 'digest')
    expect(await createScopeId(['french'])).toBe('DSLmihOUubL6ePkL')
    expect(digest).toHaveBeenCalledOnce()
    expect(digest).toHaveBeenCalledWith('SHA-256', expect.any(Uint8Array))
    expect(nobleSha256).not.toHaveBeenCalled()
  })

  test.each(SHA256_IMPLEMENTATIONS.filter(({crypto}) => crypto !== 'native'))(
    'falls back to $name',
    async implementation => {
      vi.stubGlobal('crypto', implementation.crypto)
      expect(await createScopeId(['french'])).toBe('DSLmihOUubL6ePkL')
      expect(nobleSha256).toHaveBeenCalledOnce()
    },
  )

  test.each(SHA256_IMPLEMENTATIONS)(
    'is async when using $name',
    async implementation => {
      if (implementation.crypto !== 'native') {
        vi.stubGlobal('crypto', implementation.crypto)
      }
      const result = createScopeId(['french'])
      expect(result).toBeInstanceOf(Promise)
      expect(await result).toBe('DSLmihOUubL6ePkL')
    },
  )

  test('rejects invalid input asynchronously, before hashing', async () => {
    const digest = vi.spyOn(globalThis.crypto.subtle, 'digest')
    const result = createScopeId([])
    expect(result).toBeInstanceOf(Promise)
    await expect(result).rejects.toThrow()
    expect(digest).not.toHaveBeenCalled()
  })
})

describe.each(SHA256_IMPLEMENTATIONS)(
  'createScopeId() with $name',
  implementation => {
    useSha256Implementation(implementation)

    // Generated by Content Lake. Every variant version id written by Content Lake
    // depends on these, so they must never change.
    test.each([
      {
        variantIds: ['french'],
        bundleId: undefined,
        expected: 'DSLmihOUubL6ePkL',
      },
      {
        variantIds: ['french'],
        bundleId: 'drafts',
        expected: 'k6ijCgF7N6CeiD62',
      },
      {
        variantIds: ['french'],
        bundleId: 'summer',
        expected: '8IhJkbgQrFXm7oBw',
      },
      // Disabled until Content Lake supports multi-variant documents. This id
      // was computed from the ADR-1 rule rather than generated by Content Lake;
      // restore it once Content Lake can generate a real one to check against.
      // {
      //   variantIds: ['de', 'fr'],
      //   bundleId: undefined,
      //   expected: 'hgnz4uQUmWbQMOwO',
      // },
    ])(
      'matches Content Lake for $variantIds in bundle $bundleId',
      async ({variantIds, bundleId, expected}) => {
        expect(await createScopeId(variantIds, bundleId)).toBe(expected)
      },
    )

    test('is 16 base62 characters', async () => {
      const names = Array.from(
        {length: 100},
        (_, index) => `n${index.toString(36)}_${'x-'.repeat(index)}`,
      )
      for (const [index, variantId] of names.entries()) {
        const bundleId =
          index % 2 === 0 ? undefined : names[names.length - index]
        expect(await createScopeId([variantId], bundleId)).toMatch(
          /^[0-9a-zA-Z]{16}$/,
        )
      }
    })

    test('accepts variant definition ids', async () => {
      expect(await createScopeId(['_.variants.french'], 'summer')).toBe(
        await createScopeId(['french'], 'summer'),
      )
    })

    test('is deterministic', async () => {
      expect(await createScopeId(['french'], 'summer')).toBe(
        await createScopeId(['french'], 'summer'),
      )
    })

    test('distinguishes variants and bundles', async () => {
      const expected = await createScopeId(['french'], 'summer')
      expect(await createScopeId(['german'], 'summer')).not.toBe(expected)
      expect(await createScopeId(['french'], 'winter')).not.toBe(expected)
    })

    test('treats the variants as a set', async () => {
      const expected = await createScopeId(['de', 'fr'], 'summer')
      expect(await createScopeId(['fr', 'de'], 'summer')).toBe(expected)
      expect(await createScopeId(['fr', 'de', 'fr'], 'summer')).toBe(expected)
      expect(await createScopeId(['de'], 'summer')).not.toBe(expected)
    })

    test('distinguishes variant set membership from bundle identity', async () => {
      expect(await createScopeId(['de', 'fr'])).not.toBe(
        await createScopeId(['de'], 'fr'),
      )
      expect(await createScopeId(['a', 'b', 'c'])).not.toBe(
        await createScopeId(['a', 'b'], 'c'),
      )
    })

    test('distinguishes variant-of-published from a bundle named like the variant', async () => {
      expect(await createScopeId(['french'])).not.toBe(
        await createScopeId(['french'], 'french'),
      )
    })

    test('distinguishes ambiguous concatenations', async () => {
      expect(await createScopeId(['ab'], 'c')).not.toBe(
        await createScopeId(['a'], 'bc'),
      )
      expect(await createScopeId(['french'], 'summer')).not.toBe(
        await createScopeId(['frenchsumm'], 'er'),
      )
    })

    test.each(['french', 'summer-2026'])('accepts name %j', async name => {
      await expect(createScopeId([name], name)).resolves.toMatch(
        /^[0-9a-zA-Z]{16}$/,
      )
    })

    test.each([
      '',
      'fr.en',
      'fr\x00en',
      'fr\x01en',
      '\x00',
      '\x01',
      '-fr',
      'frånçais',
    ])('rejects variant ID %j', async variantId => {
      await expect(createScopeId([variantId])).rejects.toThrow(
        /^Not a valid variant ID/,
      )
    })

    // `$published` is an internal Content Lake sentinel that never appears on the
    // wire, so here the published bundle is only addressed by omission.
    test.each(['', '$published', 'summer.2026', 'fr\x00en', 'fr\x01en'])(
      'rejects bundle ID %j',
      async bundleId => {
        await expect(createScopeId(['fr'], bundleId)).rejects.toThrow(
          /^Not a valid bundle ID/,
        )
      },
    )
  },
)

// Input is validated before hashing, so these don't vary by implementation.
describe('createScopeId() input validation', () => {
  test('rejects an empty variant set', async () => {
    await expect(createScopeId([])).rejects.toThrowErrorMatchingInlineSnapshot(
      `[Error: Must provide at least one variant ID]`,
    )
  })

  test('reports an invalid variant ID as provided', async () => {
    await expect(
      createScopeId(['fr.en']),
    ).rejects.toThrowErrorMatchingInlineSnapshot(
      `[Error: Not a valid variant ID: "fr.en" – must match the /^[a-zA-Z0-9_][a-zA-Z0-9_-]*$/ RegExp.]`,
    )
  })

  test('reports an invalid variant definition ID as provided', async () => {
    await expect(
      createScopeId(['_.variants.']),
    ).rejects.toThrowErrorMatchingInlineSnapshot(
      `[Error: Not a valid variant ID: "_.variants." – must match the /^[a-zA-Z0-9_][a-zA-Z0-9_-]*$/ RegExp once the "_.variants." prefix is removed.]`,
    )
  })

  test('explains how to address the published bundle', async () => {
    await expect(
      createScopeId(['fr'], '$published'),
    ).rejects.toThrowErrorMatchingInlineSnapshot(
      `[Error: Not a valid bundle ID: "$published" – must match the /^[a-zA-Z0-9_][a-zA-Z0-9_-]*$/ RegExp. Omit the bundle ID to address the published bundle.]`,
    )
  })
})
