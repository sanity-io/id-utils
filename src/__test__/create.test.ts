test('create variant version id from variant definition ids', async () => {
  expect(
    await createVariantVersionId({
      documentId: PublishedId('foo'),
      variantIds: createVariantDefinitionId('french'),
    }),
  ).toEqual('versions.DSLmihOUubL6ePkL.foo')
  // Both forms name the same variant, so they are one member of the set.
  expect(
    await createVariantVersionId({
      documentId: PublishedId('foo'),
      variantIds: ['_.variants.french', 'french'],
    }),
  ).toEqual('versions.DSLmihOUubL6ePkL.foo')
})

test('create variant version id rejects multi-segment variant definition ids', async () => {
  await expect(
    createVariantVersionId({
      documentId: PublishedId('foo'),
      variantIds: ['_.variants.foo.bar'],
    }),
  ).rejects.toThrowErrorMatchingInlineSnapshot(
    `[Error: Not a valid variant ID: "_.variants.foo.bar" – must match the /^[a-zA-Z0-9_][a-zA-Z0-9_-]*$/ RegExp once the "_.variants." prefix is removed.]`,
  )
})

test('create variant version id from draft and version ids', async () => {
  const expected = 'versions.8IhJkbgQrFXm7oBw.foo.bar'
  for (const documentId of [
    PublishedId('foo.bar'),
    DraftId('drafts.foo.bar'),
    VersionId('versions.xyz.foo.bar'),
  ]) {
    expect(
      await createVariantVersionId({
        documentId,
        variantIds: ['french'],
        bundleId: 'summer',
      }),
    ).toEqual(expected)
  }
})

test('create variant version id has the shape versions.{scopeId}.{id}', async () => {
  const id = await createVariantVersionId({
    documentId: PublishedId('page-1'),
    variantIds: ['french'],
    bundleId: 'summer',
  })
  const segments = id.split('.')
  expect(segments).toHaveLength(3)
  expect(segments[0]).toBe('versions')
  expect(segments[1]).toHaveLength(16)
  expect(segments[2]).toBe('page-1')
})

test.each([
  {name: 'published', bundleId: undefined},
  {name: 'drafts', bundleId: 'drafts'},
  {name: 'release', bundleId: 'summer'},
])(
  'create variant version id validates as a version id ($name)',
  async ({bundleId}) => {
    const id = await createVariantVersionId({
      documentId: PublishedId('page-1'),
      variantIds: ['french'],
      bundleId,
    })
    expect(() => VersionId(id)).not.toThrow()
    expect(() => DocumentId(id)).not.toThrow()
  },
)

