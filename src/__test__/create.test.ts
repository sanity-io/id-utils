test('create variant version id rejects system documents before hashing', async () => {
  const digest = vi.spyOn(globalThis.crypto.subtle, 'digest')
  await expect(
    createVariantVersionId({
      documentId: PublishedId('_.variants.german'),
      variantIds: ['french'],
      bundleId: 'summer',
    }),
  ).rejects.toThrowErrorMatchingInlineSnapshot(
    `[Error: Cannot create a variant version ID for "_.variants.german" – variants of system documents are not permitted]`,
  )
  expect(digest).not.toHaveBeenCalled()
})

test('create variant version id rejects a null bundle ID', async () => {
  await expect(
    createVariantVersionId({
      documentId: PublishedId('foo'),
      variantIds: ['french'],
      bundleId: null as unknown as string,
    }),
  ).rejects.toThrowErrorMatchingInlineSnapshot(
    `[Error: Not a valid bundle ID – must be a string, received null. Omit the bundle ID to address the published bundle.]`,
  )
})

// Values untyped callers (e.g. JSON) can pass where a string is expected.
const NON_STRING_VALUES = [
  {value: null, type: 'null'},
  {value: 42, type: 'number'},
  {value: true, type: 'boolean'},
  {value: {}, type: 'object'},
  {value: ['french'], type: 'array'},
]

test.each([...NON_STRING_VALUES, {value: undefined, type: 'undefined'}])(
  'create variant version id rejects a $type document ID',
  async ({value, type}) => {
    await expect(
      createVariantVersionId({
        documentId: value as unknown as DocumentId,
        variantIds: ['french'],
      }),
    ).rejects.toThrow(
      `Not a valid document ID – must be a string, received ${type}.`,
    )
  },
)

test.each([
  ...NON_STRING_VALUES.filter(({type}) => type !== 'array'),
  {value: undefined, type: 'undefined'},
])(
  'create variant version id rejects $type variant IDs',
  async ({value, type}) => {
    await expect(
      createVariantVersionId({
        documentId: PublishedId('foo'),
        variantIds: value as unknown as string,
      }),
    ).rejects.toThrow(
      `Not a valid list of variant IDs – must be a string or an array of strings, received ${type}.`,
    )
  },
)

test.each([...NON_STRING_VALUES, {value: undefined, type: 'undefined'}])(
  'create variant version id rejects a $type variant ID',
  async ({value, type}) => {
    await expect(
      createVariantVersionId({
        documentId: PublishedId('foo'),
        variantIds: ['french', value as unknown as string],
      }),
    ).rejects.toThrow(
      `Not a valid variant ID – must be a string, received ${type}.`,
    )
  },
)

test.each(NON_STRING_VALUES)(
  'create variant version id rejects a $type bundle ID',
  async ({value, type}) => {
    await expect(
      createVariantVersionId({
        documentId: PublishedId('foo'),
        variantIds: ['french'],
        bundleId: value as unknown as string,
      }),
    ).rejects.toThrow(
      `Not a valid bundle ID – must be a string, received ${type}. Omit the bundle ID to address the published bundle.`,
    )
  },
)
